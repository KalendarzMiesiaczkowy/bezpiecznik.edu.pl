"""Generate app/test/czat/retrieval/query_vectors.json from the Python pipeline."""
import json, sqlite3, sys
sys.path.insert(0, "tools")
from kb_normalize import build_match_query, load_stopwords, load_synonym_map, search

conn = sqlite3.connect("app/assets/generated/kb.sqlite")
syn = load_synonym_map(conn)
sw = load_stopwords()
queries = [
    "co robić gdy wyje syrena", "ile wody na osobę", "jak uciskać klatkę piersiową",
    "powódź ewakuacja", "brak prądu", "krwotok z nogi", "zadławił się",
    "dziecko się zadławiło", "co zabrać do plecaka ewakuacyjnego", "pożar w mieszkaniu",
    "jak ułożyć w pozycji bocznej", "co robic gdy wyje syrena", "powodz", "jak uciskac klatke",
    "jak zrobić ciasto czekoladowe", "kto wygra mecz", "przepis na pierogi",
    "jaka będzie pogoda jutro", "kurs bitcoina", "jak naprawić agregat prądotwórczy diesla",
    'NEAR(a b) OR "x" * (y) -z', "", "co to jest", "ŁÓDŹ  Żółć!!", "  112  ", "a b c do",
    "Nie oddycha, co robić?", "zasięg komórkowy zanik", "AND OR NOT NEAR",
]
out = []
for q in queries:
    out.append({
        "query": q,
        "match": build_match_query(q, syn, sw),
        "top": [[i, round(s, 6)] for i, s in search(conn, q, syn, sw, limit=4)],
    })
json.dump({"description": "Generated by tools/gen_query_vectors.py from tools/kb_normalize.py against assets/generated/kb.sqlite. Dart must reproduce `match` exactly; top ids/scores are checked only when the built kb.sqlite has the same meta.built_at.",
           "built_at": conn.execute("select value from meta where key='built_at'").fetchone()[0],
           "vectors": out}, open("app/test/czat/retrieval/query_vectors.json", "w"),
          ensure_ascii=False, indent=1)
print(len(out))
